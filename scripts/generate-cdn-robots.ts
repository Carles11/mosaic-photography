import { config } from "dotenv";
config();
config({ path: ".env.local", override: true });
import { createClient } from "@supabase/supabase-js";
import fs from "fs";
import path from "path";
// For Node.js < 22
import ws from "ws";
// @ts-ignore
global.WebSocket = ws;

// Initialize Supabase client (same pattern as other scripts)
const supabaseUrl = process.env.NEXT_PUBLIC_SUPABASE_URL || "";
const supabaseKey = process.env.SUPABASE_SERVICE_ROLE_KEY || "";
const supabase = createClient(supabaseUrl, supabaseKey);

type FlaggedImage = {
  base_url: string | null;
  filename: string | null;
};

function getPathFromBaseUrl(baseUrl: string): string {
  try {
    const url = new URL(baseUrl);
    return url.pathname.replace(/\/$/, "");
  } catch {
    // If it's not a full URL, try to extract path-like part
    if (baseUrl.startsWith("http")) return "";
    // assume it's already a path
    return baseUrl.replace(/\/$/, "");
  }
}

function getFilenameStem(filename: string): string {
  return filename.replace(/\.[^/.]+$/, "");
}

async function generateCdnRobots() {
  const { data, error } = await supabase
    .from("images_resize")
    .select("base_url, filename")
    .eq("exclude_from_index", true);

  if (error) {
    console.error("Error fetching excluded images:", error);
    process.exit(1);
  }

  if (!data || data.length === 0) {
    console.error("No images found with exclude_from_index = true. Migration may not have run.");
    process.exit(1);
  }

  const images = data as FlaggedImage[];
  const disallows = new Set<string>();

  for (const img of images) {
    if (!img.base_url || !img.filename) continue;
    const path = getPathFromBaseUrl(img.base_url);
    const stem = getFilenameStem(img.filename);
    if (!path || !stem) continue;
    disallows.add(`${path}/*/${stem}.webp`);
  }

  let content = `# robots.txt for cdn.mosaic.photography — generated by scripts/generate-cdn-robots.ts
# Images kept on www.mosaic.photography but excluded from search indexes (2026-10-24).
User-agent: *
Allow: /
`;

  // Sort for deterministic output
  const sorted = Array.from(disallows).sort();
  for (const d of sorted) {
    content += `Disallow: ${d}\n`;
  }

  const outDir = path.join(process.cwd(), "cdn-robots");
  if (!fs.existsSync(outDir)) {
    fs.mkdirSync(outDir, { recursive: true });
  }
  const outPath = path.join(outDir, "robots.txt");
  fs.writeFileSync(outPath, content);
  console.log(`Wrote ${outPath} with ${sorted.length} Disallow rules`);
}

generateCdnRobots().catch((err) => {
  console.error(err);
  process.exit(1);
});
